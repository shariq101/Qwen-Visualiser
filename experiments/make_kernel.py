"""
Build a single-file Kaggle script kernel from suite.py + corpus.py.

Kaggle's `kernels push` uploads exactly one code file, so the two modules are
concatenated here. Run this, then:

    kaggle kernels push -p experiments/kaggle
    kaggle kernels status skrik001/depth-atlas-qwen
    kaggle kernels output skrik001/depth-atlas-qwen -p /tmp/atlas_out

The kernel writes public/data JSON into /kaggle/working/data, which is what
`kaggle kernels output` downloads.
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
KAGGLE = ROOT / "experiments" / "kaggle"
KAGGLE.mkdir(parents=True, exist_ok=True)

corpus = (ROOT / "experiments" / "corpus.py").read_text()
suite = (ROOT / "experiments" / "suite.py").read_text()

# The kernel is a single file: drop the local import and the sys.path shim.
suite = suite.replace(
    "sys.path.insert(0, str(Path(__file__).resolve().parent))\nfrom corpus import ABLATION_IDS, CORPUS, DEEP_DIVE_IDS  # noqa: E402\n",
    "",
)
suite = suite.replace(
    "sys.path.insert(0, str(Path(__file__).resolve().parent))\n", ""
)
# A future import is only legal at the very top of a module; the corpus is
# concatenated above the suite, so hoist it into the header.
suite = suite.replace("from __future__ import annotations\n", "")

header = '''# Depth Atlas - Kaggle GPU run (autogenerated by experiments/make_kernel.py)
from __future__ import annotations
import os
os.environ.setdefault("ATLAS_OUT", "/kaggle/working/data")
os.environ.setdefault("QWEN_CACHE", "/kaggle/working/cache")
os.environ.setdefault("MODEL_ID", "Qwen/Qwen2.5-3B-Instruct")
os.environ.setdefault("DTYPE", "float16")
print("model:", os.environ["MODEL_ID"], flush=True)
'''

footer = '''
if __name__ == "__main__":
    for stage in ("capture", "ablate", "analyse", "graph", "build"):
        log(f"===== {stage} =====")
        {"capture": capture, "ablate": ablate, "analyse": analyse,
         "graph": graph, "build": build}[stage]()
    log("kernel finished; artefacts in " + str(OUT))
'''

# Strip the original entrypoint so it is not run twice.
suite = suite.split('if __name__ == "__main__":')[0]

(KAGGLE / "suite_kaggle.py").write_text(header + "\n" + corpus + "\n\n" + suite + footer)

meta = {
    "id": "skrik001/depth-atlas-qwen",
    "title": "Depth Atlas Qwen",
    "code_file": "suite_kaggle.py",
    "language": "python",
    "kernel_type": "script",
    "is_private": True,
    "enable_gpu": True,
    "enable_internet": True,
    "dataset_sources": [],
    "competition_sources": [],
    "kernel_sources": [],
}
(KAGGLE / "kernel-metadata.json").write_text(json.dumps(meta, indent=2))
print("wrote", KAGGLE / "suite_kaggle.py", (KAGGLE / "suite_kaggle.py").stat().st_size, "bytes")
